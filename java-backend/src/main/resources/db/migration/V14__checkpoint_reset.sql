-- ============================================================
-- 位点重置（PITR）：把"这条位点是被人工重置过的"这件事本身持久化下来。
--
-- 为什么需要一列而不是直接改 payload 就完事：重置是在<b>后端</b>做的，而位点的实际使用方
-- 是 agent 本地的老载体（capture_position.properties / H2）。只改中心库，agent 一看
-- "本地有位点" 就走同机重启分支，重置的结果永远不会生效。
--
-- 有了 reset_at，agent 的回灌判据多一条：中心位点的 reset_at 比本地位点的时间新
--  → 强制用中心位点覆盖本地（这是唯一允许位点"倒退"的路径，且必有 RESET 审计记录）。
-- ============================================================
ALTER TABLE task_checkpoints
    ADD COLUMN reset_at DATETIME(3) DEFAULT NULL
        COMMENT '最近一次人工重置时刻；比本地位点新即触发强制回灌（唯一允许位点倒退的路径）';
